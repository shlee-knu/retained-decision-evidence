from logistics_validation.standards_core import CompiledModel, canonical, digest, selected


def dump(path, value):
    with path.open("x") as f:
        json.dump(value, f, indent=2, ensure_ascii=False)
        f.write("\n")


class BlockCodec:
    """An explicit local grouped-JSON adapter, not a standard network endpoint."""
    def __init__(self, model, encode):
        self.model = model
        self.encode = encode
        self.payloads = [dict() for _ in model.block_names]
        self.reverse = [dict() for _ in model.block_names]
        for state in model.states:
            row = encode(state)
            if set(row) != set(model.block_names):
                raise ValueError("encode_state must return exactly the named blocks")
            for block, name in enumerate(model.block_names):
                payload = canonical(row[name])
                category = state[block]
                if category in self.payloads[block] and self.payloads[block][category] != payload:
                    raise ValueError("payload depends on an unobserved block: " + name)
                if payload in self.reverse[block] and self.reverse[block][payload] != category:
                    raise ValueError("category-to-payload encoding must be injective: " + name)
                self.payloads[block][category] = payload
                self.reverse[block][payload] = category

    def category(self, block, payload):
        try:
            return self.reverse[block][canonical(payload)]
        except KeyError as e:
            raise ValueError("unsupported complete block payload") from e

    def record(self, index):
        m = self.model
        state = m.states[index]
        payload = self.encode(state)
        snapshot = digest(payload)
        mask, reads = m.recover(index, 0, "old")
        observations = {m.block_names[b]: state[b] for b in selected(mask, m.count)}
        retained = {name: payload[name] for name in observations}
        receipt = dict(domain_sha256=m.domain_digest, old_predicate_sha256=m.old_digest,
                       snapshot_sha256=snapshot, verdict=m.old_labels[index],
                       observations=observations, payloads=retained)
        source = {name: canonical(value) for name, value in payload.items()}
        return dict(index=index, mask=mask, old_reads=len(reads), snapshot=snapshot,
                    source=source, bundled=canonical(payload), receipt=canonical(receipt))

    def load_receipt(self, text, expected_snapshot, diagnose=False, verify_old=True):
        receipt = json.loads(text)
        if not isinstance(receipt, dict):
            raise ValueError("malformed receipt")
        observations = receipt.get("observations", {})
        if not isinstance(observations, dict) or not isinstance(receipt.get("payloads"), dict):
            raise ValueError("malformed observations or payloads")
        if set(receipt.get("payloads", {})) != set(observations):
            raise ValueError("receipt payload coverage mismatch")
        for name, payload in receipt["payloads"].items():
            block = self.model.block_names.index(name)
            if self.category(block, payload) != observations[name]:
                raise ValueError("receipt category does not match retained payload")
        m = self.model
        if (receipt.get("domain_sha256") != m.domain_digest
                or receipt.get("old_predicate_sha256") != m.old_digest
                or receipt.get("snapshot_sha256") != expected_snapshot):
            raise ValueError("receipt binding mismatch")
        index, mask = m.representative(observations)
        if verify_old and (type(receipt.get("verdict")) is not bool or m.outcomes(index, mask, "old") != {receipt["verdict"]}):
            raise ValueError("insufficient old evidence")
        check = m.check_receipt(receipt, expected_snapshot) if diagnose else None
        return receipt, check


class Accessor:
    def __init__(self, record, codec, layout):
        self.record, self.codec, self.layout = record, codec, layout
        self.reads = []
        self.delivered = set()
        self.requests = 0
        self.bytes = 0
        self.bundle = None

    def read(self, block):
        if block in self.reads:
            raise AssertionError("duplicate logical block acquisition")
        self.reads.append(block)
        name = self.codec.model.block_names[block]
        if self.layout == "separate":
            raw = self.record["source"][name]
            self.requests += 1
            self.bytes += len(raw.encode())
            payload = json.loads(raw)
            self.delivered.add(block)
        else:
            if self.bundle is None:
                raw = self.record["bundled"]
                self.requests += 1
                self.bytes += len(raw.encode())
                self.bundle = json.loads(raw)
                self.delivered.update(range(self.codec.model.count))
            payload = self.bundle[name]
        return self.codec.category(block, payload)


def run_case(model, codec, record, strategy, layout, static_plan):
    source = Accessor(record, codec, layout)
    receipt_bytes = 0
    receipt_requests = 0
    status = None
    if strategy in {"ordinary_cached", "static_delta", "receipt_audit"}:
        # Recomputing from retained values needs truthful values and binding,
        # but does not need the old verdict to be a valid certificate.
        receipt, check = codec.load_receipt(record["receipt"], record["snapshot"],
                                           diagnose=strategy == "receipt_audit",
                                           verify_old=strategy != "ordinary_cached")
        known = dict(receipt["observations"])
        receipt_bytes = len(record["receipt"].encode())
        receipt_requests = 1
        if strategy == "receipt_audit":
            status = check["status"]
            if "witness" in check:
                # Materialize diagnostic completions; ordinary recomputation
                # does not promise this additional output service.
                canonical([codec.encode(model.states[i]) for i in check["witness"]])
    else:
        known = {}
    index, mask = model.representative(known)
    previously_known = set(known)

    def acquire(block):
        known[model.block_names[block]] = source.read(block)
        if source.bundle is not None:
            # A fetched complete bundle makes all fields available immediately;
            # no repeated policy steps are charged after the bundled delivery.
            for b, name in enumerate(model.block_names):
                known[name] = codec.category(b, source.bundle[name])

    if strategy == "full_fragment":
        requested = tuple(range(model.count))
    elif strategy == "static_delta":
        requested = selected(static_plan[receipt["verdict"]]["mask"] & ~mask, model.count)
    else:
        requested = ()
    for block in requested:
        if model.block_names[block] not in known:
            acquire(block)
    index, mask = model.representative(known)
    if strategy in {"ordinary_cached", "receipt_audit", "fresh_guarded"}:
        while len(model.outcomes(index, mask)) > 1:
            influence = model.influential(index, mask)
            block = next(i for i in range(model.count) if influence & (1 << i))
            acquire(block)
            index, mask = model.representative(known)
    values = model.outcomes(index, mask)
    if len(values) != 1:
        raise AssertionError("retrieval plan left the new verdict ambiguous")
    verdict = next(iter(values))
    if verdict != model.new_labels[record["index"]]:
        raise AssertionError("complete-fragment verdict mismatch")
    # Equal output contract: every strategy emits all available observed evidence,
    # not just a Boolean; no discarded historical acquisition is refunded.
    replacement = dict(domain_sha256=model.domain_digest, predicate_sha256=model.new_digest,
                       snapshot_sha256=record["snapshot"], verdict=verdict, observations=known,
                       payloads={name: json.loads(codec.payloads[model.block_names.index(name)][category])
                                 for name, category in known.items()})
    emitted_bytes = len(canonical(replacement).encode())
    return dict(verdict=verdict, status=status, logical_blocks=len(source.delivered),
                explicitly_requested_blocks=len(source.reads), newly_observed_blocks=len(set(known)-previously_known),
                source_requests=source.requests, source_bytes=source.bytes,
                receipt_requests=receipt_requests, receipt_bytes=receipt_bytes,
                emitted_bytes=emitted_bytes)


def audit_model(spec, directory, repeats):
    started = time.process_time_ns()
    model = CompiledModel(spec)
    compile_ns = time.process_time_ns() - started
    started = time.process_time_ns()
    codec = BlockCodec(model, spec["encode_state"])
    codec_ns = time.process_time_ns() - started
    metadata = spec.get("metadata", {})
    changed_names = metadata.get("changed_dependencies", model.block_names)
    static_plan = model.static_delta_plan(changed_names)
    # Precompute the shared finite query planner for every observation fiber;
    # runtime timings are warm replays and compilation/preparation are separate.
    started = time.process_time_ns()
    for version in ("old", "new"):
        for index, mask in model.observation_classes(version, sufficient_only=False):
            model.influential(index, mask, version)
    planner_ns = time.process_time_ns() - started
    started = time.process_time_ns()
    records = [codec.record(i) for i in range(len(model.states))]
    record_preparation_ns = time.process_time_ns() - started
    statuses = Counter()
    witness_rows = []
    classes = []
    checks = 0
    for index, mask in model.observation_classes():
        status = model.classify(index, mask, model.old_labels[index])
        statuses[status] += 1
        row = dict(representative=index, retained_mask=mask, status=status)
        if status == "insufficient":
            pair = model.witness(index, mask)
            assert pair and model.new_labels[pair[0]] != model.new_labels[pair[1]]
            assert all(model.states[pair[0]][b] == model.states[pair[1]][b]
                       for b in selected(mask, model.count))
            assert model.old_labels[pair[0]] == model.old_labels[pair[1]] == model.old_labels[index]
            row["witness"] = list(pair)
            witness_rows.append(dict(mask=mask, pair=list(pair),
                                     false_completion=codec.encode(model.states[pair[0]]),
                                     true_completion=codec.encode(model.states[pair[1]])))
            checks += 3
        classes.append(row)
        checks += 1
    masks_changed = sum(model.minimal_masks(i, "old") != model.minimal_masks(i, "new")
                        for i in range(len(model.states)))
    preserved_changed = sum(model.old_labels[i] == model.new_labels[i]
                            and model.minimal_masks(i, "old") != model.minimal_masks(i, "new")
                            for i in range(len(model.states)))
    with gzip.open(directory / (model.name + "_classes.jsonl.gz"), "wt") as f:
        for row in classes:
            f.write(canonical(row) + "\n")
    with gzip.open(directory / (model.name + "_witnesses.jsonl.gz"), "wt") as f:
        for row in witness_rows:
            f.write(canonical(row) + "\n")
    with gzip.open(directory / (model.name + "_receipts.jsonl.gz"), "wt") as f:
        for r in records:
            f.write(r["receipt"] + "\n")
    receipt_status = Counter(model.classify(r["index"], r["mask"], model.old_labels[r["index"]])
                             for r in records)
    minimum_additions = sum(min(m.bit_count() for m in model.minimal_additions(r["index"], r["mask"]))
                            for r in records)
    benchmark = []
    strategies = ("full_fragment", "fresh_guarded", "ordinary_cached", "static_delta", "receipt_audit")
    for layout in ("separate", "bundled"):
        # Rotate strategy order across measured rounds, preserving all raw rows.
        for round_no in range(-1, repeats):
            order = strategies[round_no % len(strategies):] + strategies[:round_no % len(strategies)]
            for strategy in order:
                totals = Counter()
                cpu = time.process_time_ns()
                wall = time.perf_counter_ns()
                for record in records:
                    row = run_case(model, codec, record, strategy, layout, static_plan)
                    for key in ("logical_blocks", "explicitly_requested_blocks", "newly_observed_blocks", "source_requests", "source_bytes", "receipt_requests",
                                "receipt_bytes", "emitted_bytes"):
                        totals[key] += row[key]
                wall = time.perf_counter_ns() - wall
                cpu = time.process_time_ns() - cpu
                if round_no >= 0:
                    benchmark.append(dict(model=model.name, layout=layout, strategy=strategy,
                                          repeat=round_no, cases=len(records), cpu_ns=cpu, wall_ns=wall,
                                          **dict(totals)))
    aggregates = []
    for layout in ("separate", "bundled"):
        for strategy in strategies:
            rows = [r for r in benchmark if r["layout"] == layout and r["strategy"] == strategy]
            first = rows[0]
            keys = ("logical_blocks", "explicitly_requested_blocks", "newly_observed_blocks", "source_requests", "source_bytes", "receipt_requests", "receipt_bytes", "emitted_bytes")
            for key in keys:
                assert len({r[key] for r in rows}) == 1
            aggregates.append(dict(layout=layout, strategy=strategy, cases=len(records),
                                   median_cpu_us_per_case=statistics.median(r["cpu_ns"] for r in rows)/len(records)/1000,
                                   median_wall_us_per_case=statistics.median(r["wall_ns"] for r in rows)/len(records)/1000,
                                   **{key: first[key] for key in keys}))
        a = next(r for r in aggregates if r["layout"] == layout and r["strategy"] == "receipt_audit")
        b = next(r for r in aggregates if r["layout"] == layout and r["strategy"] == "ordinary_cached")
        assert all(a[k] == b[k] for k in ("logical_blocks", "source_requests", "source_bytes"))
        checks += 3
    summary = dict(name=model.name, blocks=list(model.block_names), states=len(model.states),
                   old_pass=sum(model.old_labels), new_pass=sum(model.new_labels),
                   label_changes=sum(a != b for a,b in zip(model.old_labels, model.new_labels)),
                   certificate_family_changes=masks_changed,
                   label_preserved_certificate_family_changes=preserved_changed,
                   valid_old_observation_classes=len(classes), classification=dict(statuses),
                   witness_pairs=len(witness_rows), generated_receipts=len(records),
                   generated_receipt_status=dict(receipt_status),
                   pointwise_minimum_additional_blocks=minimum_additions,
                   historical_old_blocks=sum(r["old_reads"] for r in records),
                   source_bindings=dict(domain_sha256=model.domain_digest,
                                        old_predicate_sha256=model.old_digest,new_predicate_sha256=model.new_digest),
                   static_delta_plan={str(k).lower(): v for k,v in static_plan.items()}, metadata=metadata,
                   setup_cpu_ns=dict(model_compilation=compile_ns, codec_check=codec_ns,
                                     shared_planner_compilation=planner_ns, synthetic_receipt_preparation=record_preparation_ns),
                   checks=checks, replay=aggregates)
    dump(directory / (model.name + "_summary.json"), summary)
    dump(directory / (model.name + "_timings.json"), benchmark)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "results/standards_extension/audit")
    parser.add_argument("--repeats", type=int, default=7)
    parser.add_argument("--models", nargs="*")
    args = parser.parse_args()
    if args.repeats < 1:
        parser.error("at least one timing repeat required")
    out = args.output.resolve()
    if out.exists() and any(out.iterdir()):
        parser.error("output exists and is populated; choose a fresh directory")
    out.mkdir(parents=True, exist_ok=True)
    from logistics_validation.standards_epcis import build_models as epcis_models, build_schema_identity_model
    from logistics_validation.standards_fhir import build_models as fhir_models
    specs = list(epcis_models()) + [build_schema_identity_model()] + list(fhir_models())
    if args.models:
        names = set(args.models)
        if names - {s["name"] for s in specs}:
            parser.error("unknown model selection")
        specs = [s for s in specs if s["name"] in names]
    started = time.perf_counter()
    results = []
    for spec in specs:
        row = audit_model(spec, out, args.repeats)
        results.append(row)
        print(canonical({k: row[k] for k in ("name", "states", "valid_old_observation_classes", "classification")}), flush=True)
    source_hashes = {}
    for pattern in ("src/logistics_validation/standards_*.py", "scripts/audit_standards_extension.py",
                    "configs/*standards*_protocol.json", "data/external/fhir_standards/profiles/*/*.json",
                    "data/external/epcis_extension/originals/*"):
        for path in sorted(ROOT.glob(pattern)):
            source_hashes[path.relative_to(ROOT).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    report = dict(status="passed", created_utc=datetime.now(timezone.utc).isoformat(), models=results,
                  timing_repeats=args.repeats, elapsed_seconds=time.perf_counter()-started,
                  source_sha256=source_hashes,
                  scope="Exhaustive supported finite fragments and synthetic local JSON replay. Not whole-standard conformance, real operations, server API performance, or a new optimal online acquisition algorithm.",
                  cost_boundary="Separate setup, historical acquisition and warm replay. Replay includes actual JSON parsing, retained-record loading/checking and replacement serialization; dictionary source, no disk/network or durable writes. Bundled source returns every named block on first request. Static delta plan is independently sound-checked over the finite domain. All cached paths use the same query planner; diagnosis is an extra service, not a read-count advantage over ordinary cache.")
    dump(out / "summary.json", report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
