"""Exhaustive named-block audit and local JSON replay of standard fragments.

No healthcare or supply-chain production rates are estimated. Receipts are
generated by a fixed, observation-adaptive old-fragment acquisition policy over
finite synthetic states. Counts are not independent natural-data sample sizes.
"""
